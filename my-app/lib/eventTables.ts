/**
 * Sanitizes an event name to a valid PostgreSQL table name slug.
 * Example: "AI & Web3 Hackathon 2026" -> "ai_web3_hackathon_2026"
 */
export function sanitizeEventTableName(eventName: string): string {
  if (!eventName) return "event_default";
  
  let slug = eventName
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');

  // PostgreSQL table names shouldn't start with a number
  if (/^[0-9]/.test(slug)) {
    slug = 'evt_' + slug;
  }

  // PostgreSQL identifier limit is 63 chars; keep slug under 40 chars
  return slug.slice(0, 40) || 'event';
}

export function getEventTableNames(eventName: string) {
  const slug = sanitizeEventTableName(eventName);
  return {
    slug,
    participantsTable: `participants_${slug}`,
    checkInTable: `check_in_logs_${slug}`,
  };
}

/**
 * Builds custom SQL for a single table given user-defined columns, names, types, and values.
 */
export function generateCustomTableSQL(
  tableName: string,
  columns: SchemaColumn[],
  comment?: string
): string {
  if (!columns.length) {
    return `-- No columns defined for ${tableName}`;
  }

  const columnLines = columns.map(col => {
    const colName = col.name.trim().toLowerCase().replace(/[^a-z0-9_]+/g, '_');
    const colType = col.type.trim() || 'TEXT';
    const parts = [`  "${colName}" ${colType}`];

    if (col.isPrimaryKey) {
      parts.push('PRIMARY KEY');
    }
    if (col.isNullable === false && !col.isPrimaryKey) {
      parts.push('NOT NULL');
    }
    if (col.isUnique && !col.isPrimaryKey) {
      parts.push('UNIQUE');
    }
    if (col.defaultValue && col.defaultValue.trim() !== '') {
      parts.push(`DEFAULT ${col.defaultValue.trim()}`);
    }

    return parts.join(' ');
  });

  return `-- Table: public."${tableName}" ${comment ? `(${comment})` : ''}
CREATE TABLE IF NOT EXISTS public."${tableName}" (
${columnLines.join(',\n')}
);

-- Enable Row Level Security and allow full access for web app
ALTER TABLE public."${tableName}" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all operations on ${tableName}" ON public."${tableName}";
CREATE POLICY "Allow all operations on ${tableName}"
  ON public."${tableName}"
  FOR ALL
  USING (true)
  WITH CHECK (true);
`;
}

/**
 * Generates custom PostgreSQL DDL script combining participants and check_in_logs tables
 * based on user-configured column names, values, and types.
 */
export function generateCustomEventTablesSQL(
  eventName: string,
  participantCols: SchemaColumn[] = DEFAULT_PARTICIPANT_COLUMNS,
  checkInCols: SchemaColumn[] = DEFAULT_CHECKIN_COLUMNS
): string {
  const { participantsTable, checkInTable } = getEventTableNames(eventName);

  const safeEventTitle = eventName.replace(/'/g, "''");

  // If user included an 'event' column without default, assign eventName
  const enrichedParticipantCols = participantCols.map(col => {
    if (col.name === 'event' && (!col.defaultValue || col.defaultValue.trim() === '')) {
      return { ...col, defaultValue: `'${safeEventTitle}'` };
    }
    return col;
  });

  const partSQL = generateCustomTableSQL(
    participantsTable,
    enrichedParticipantCols,
    `Participants table for "${eventName}"`
  );

  const checkSQL = generateCustomTableSQL(
    checkInTable,
    checkInCols,
    `Check-in logs table for "${eventName}"`
  );

  return `-- ============================================================
-- DEDICATED SCHEMA FOR EVENT: ${eventName}
-- Generated on ${new Date().toISOString()}
-- Copy & Run in Supabase Dashboard -> SQL Editor
-- ============================================================

${partSQL}

${checkSQL}
`;
}

/**
 * Default generator (backwards-compatible with previous call sites).
 */
export function generateEventTablesSQL(eventName: string): string {
  return generateCustomEventTablesSQL(eventName, DEFAULT_PARTICIPANT_COLUMNS, DEFAULT_CHECKIN_COLUMNS);
}

/**
 * Checks if a table already exists in Supabase.
 */
export async function checkTableExists(tableName: string): Promise<boolean> {
  try {
    const { error } = await supabase.from(tableName).select('*').limit(1);
    if (!error) return true;
    if (error.code === '42P01' || error.message?.includes('does not exist')) {
      return false;
    }
    return false;
  } catch {
    return false;
  }
}

/**
 * Attempts to automatically create event tables via Supabase RPC or API endpoint.
 */
export async function provisionEventTables(eventName: string, customSQL?: string): Promise<{
  success: boolean;
  participantsTable: string;
  checkInTable: string;
  message: string;
  sql: string;
  method: 'rpc' | 'manual';
}> {
  const { participantsTable, checkInTable, slug } = getEventTableNames(eventName);
  const sql = customSQL || generateEventTablesSQL(eventName);

  // 1. If customSQL is provided, try execute_ddl RPC
  if (customSQL) {
    try {
      const { data, error } = await supabase.rpc('execute_ddl', { sql_statement: customSQL });
      if (!error && (data?.success || data === true)) {
        return {
          success: true,
          participantsTable,
          checkInTable,
          message: `Custom tables '${participantsTable}' & '${checkInTable}' successfully created!`,
          sql,
          method: 'rpc',
        };
      }
    } catch (e) {
      console.warn("execute_ddl failed, falling back to standard create_event_tables", e);
    }
  }

  // 2. Try standard create_event_tables RPC
  try {
    const { data, error } = await supabase.rpc('create_event_tables', {
      event_slug: slug,
      event_name: eventName,
    });

    if (!error && (data?.success || data === true)) {
      return {
        success: true,
        participantsTable,
        checkInTable,
        message: `Dedicated tables '${participantsTable}' and '${checkInTable}' successfully created in Supabase!`,
        sql,
        method: 'rpc',
      };
    }
  } catch (rpcErr) {
    console.warn("Supabase RPC create_event_tables not available or failed:", rpcErr);
  }

  // 3. Check if table already exists
  const exists = await checkTableExists(participantsTable);
  if (exists) {
    return {
      success: true,
      participantsTable,
      checkInTable,
      message: `Dedicated tables '${participantsTable}' and '${checkInTable}' are active in database!`,
      sql,
      method: 'rpc',
    };
  }

  // 4. Fallback: Return generated SQL for copy/paste
  return {
    success: false,
    participantsTable,
    checkInTable,
    message: `SQL script generated. Copy the SQL script and run it in your Supabase SQL Editor.`,
    sql,
    method: 'manual',
  };
}

/**
 * Searches for a participant across all known event dedicated tables, unified participants, and local cache.
 */
export async function findParticipantAcrossTables(id: string): Promise<{
  participant: any | null;
  sourceTable: string | null;
  checkInTable: string | null;
  isCheckedIn: boolean;
}> {
  if (!id) return { participant: null, sourceTable: null, checkInTable: null, isCheckedIn: false };

  const cleanId = decodeURIComponent(id).trim();
  const vishakaVariant = cleanId.replace(/splash/gi, "Vishaka");
  const splashVariant = cleanId.replace(/vishaka/gi, "Splash");

  // 1. Get candidate tables from all registered events
  const candidateTables: { participantsTable: string; checkInTable: string }[] = [];
  try {
    const { data: events } = await supabase.from('events').select('title, code');
    if (events && events.length > 0) {
      for (const e of events) {
        candidateTables.push(getEventTableNames(e.title));
      }
    }
  } catch {}

  // Known fallback candidates
  candidateTables.push({ participantsTable: 'participants_ignite2k26', checkInTable: 'check_in_logs_ignite2k26' });
  candidateTables.push({ participantsTable: 'participants_vishaka_2026', checkInTable: 'check_in_logs_vishaka_2026' });
  candidateTables.push({ participantsTable: 'participants', checkInTable: 'check_in_logs' });

  // 2. Search candidate tables in parallel/sequence
  for (const { participantsTable, checkInTable } of candidateTables) {
    try {
      const { data, error } = await supabase
        .from(participantsTable)
        .select('*')
        .or(`participant_id.eq.${cleanId},participant_id.eq.${vishakaVariant},participant_id.eq.${splashVariant},id.eq.${cleanId}`)
        .limit(1);

      if (!error && data && data.length > 0) {
        const item = data[0];
        let isCheckedIn = item.status === 'checked-in';
        try {
          const { data: logData } = await supabase
            .from(checkInTable)
            .select('id')
            .eq('participant_id', item.participant_id || cleanId)
            .limit(1);
          if (logData && logData.length > 0) isCheckedIn = true;
        } catch {}

        return {
          participant: item,
          sourceTable: participantsTable,
          checkInTable,
          isCheckedIn,
        };
      }
    } catch {}
  }

  // 3. Fallback to localStorage in browser
  if (typeof window !== 'undefined') {
    try {
      for (let i = 0; i < localStorage.length; i++) {
        const key = localStorage.key(i);
        if (key && key.startsWith('local_participants_')) {
          const items = JSON.parse(localStorage.getItem(key) || '[]');
          const match = items.find((p: any) => 
            p.participant_id === cleanId || p.participant_id === vishakaVariant || p.id === cleanId
          );
          if (match) {
            return {
              participant: match,
              sourceTable: 'localStorage',
              checkInTable: null,
              isCheckedIn: match.status === 'checked-in',
            };
          }
        }
      }
    } catch {}
  }

  return { participant: null, sourceTable: null, checkInTable: null, isCheckedIn: false };
}

