-- ============================================================
-- VISHAKA 2K26: Dynamic Per-Event Table Provisioner RPC
-- Run this ONCE in your Supabase Dashboard -> SQL Editor.
-- It enables the web app to automatically create dedicated 
-- 'participants_<event_name>' and 'check_in_logs_<event_name>'
-- tables on demand from the admin dashboard!
-- ============================================================

CREATE OR REPLACE FUNCTION public.create_event_tables(
  event_slug TEXT,
  event_name TEXT DEFAULT ''
)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER -- Runs with elevated admin privileges to execute CREATE TABLE
AS $$
DECLARE
  clean_slug TEXT;
  t_participants TEXT;
  t_check_in TEXT;
BEGIN
  -- 1. Sanitize the slug to ensure safety against SQL injection
  clean_slug := lower(regexp_replace(event_slug, '[^a-zA-Z0-9_]', '_', 'g'));
  clean_slug := regexp_replace(clean_slug, '_+', '_', 'g');
  clean_slug := trim(both '_' from clean_slug);

  IF clean_slug ~ '^[0-9]' THEN
    clean_slug := 'evt_' || clean_slug;
  END IF;

  IF length(clean_slug) = 0 THEN
    clean_slug := 'event';
  END IF;

  t_participants := 'participants_' || substr(clean_slug, 1, 40);
  t_check_in := 'check_in_logs_' || substr(clean_slug, 1, 40);

  -- 2. Create the dedicated Participants table for this event
  EXECUTE format('
    CREATE TABLE IF NOT EXISTS public.%I (
      id TEXT PRIMARY KEY,
      participant_id TEXT NOT NULL,
      participant_name TEXT NOT NULL,
      register_number TEXT NOT NULL,
      year TEXT,
      department TEXT,
      section TEXT,
      game TEXT,
      email TEXT,
      mobile TEXT,
      category TEXT,
      cultural_interest TEXT,
      status TEXT DEFAULT ''registered'',
      event TEXT DEFAULT %L,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone(''utc''::text, now()),
      updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone(''utc''::text, now())
    );

    ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;

    DROP POLICY IF EXISTS "Allow all on %I" ON public.%I;
    CREATE POLICY "Allow all on %I"
      ON public.%I
      FOR ALL
      USING (true)
      WITH CHECK (true);
  ', t_participants, coalesce(event_name, clean_slug), t_participants, t_participants, t_participants, t_participants, t_participants);

  -- 3. Create the dedicated Check-in Logs table for this event
  EXECUTE format('
    CREATE TABLE IF NOT EXISTS public.%I (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      participant_id TEXT NOT NULL,
      logged_at TIMESTAMP WITH TIME ZONE DEFAULT timezone(''utc''::text, now()),
      scanner_id TEXT,
      status TEXT DEFAULT ''checked-in'',
      remarks TEXT
    );

    ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;

    DROP POLICY IF EXISTS "Allow all on %I" ON public.%I;
    CREATE POLICY "Allow all on %I"
      ON public.%I
      FOR ALL
      USING (true)
      WITH CHECK (true);
  ', t_check_in, t_check_in, t_check_in, t_check_in, t_check_in);

  -- 4. Return success result
  RETURN json_build_object(
    'success', true,
    'event_slug', clean_slug,
    'participants_table', t_participants,
    'check_in_table', t_check_in,
    'message', 'Dedicated event tables created successfully'
  );
EXCEPTION WHEN OTHERS THEN
  RETURN json_build_object(
    'success', false,
    'error', SQLERRM
  );
END;
$$;

-- Grant execution permissions to anon and authenticated users
GRANT EXECUTE ON FUNCTION public.create_event_tables(TEXT, TEXT) TO anon;
GRANT EXECUTE ON FUNCTION public.create_event_tables(TEXT, TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.create_event_tables(TEXT, TEXT) TO service_role;
